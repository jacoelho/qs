// file accumulates one generated source file.
type file struct{ source []byte }

func (f *file) write(text string) { f.source = append(f.source, text...) }

func (f *file) printf(format string, args ...any) { f.source = fmt.Appendf(f.source, format, args...) }

func (f *file) doc(name, text string) { f.printf("// %s %s\n", name, text) }

// method declares one value-receiver method on builder. A result of "" means
// the builder's own type.
func (f *file) method(builder, name, params, result, body string) {
	f.genericMethod(builder, name, "", params, result, body)
}

// genericMethod is method with a type parameter list such as "[T any]".
func (f *file) genericMethod(builder, name, typeParams, params, result, body string) {
	f.doc(name, docs[name])
	if result == "" {
		result = builder
	}
	f.printf("func (b %s) %s%s(%s) %s { %s }\n", builder, name, typeParams, params, result, body)
}

func statementMethods() *file {
	f := new(file)
	f.write(header)
	for _, k := range statementKinds {
		t := k.builder
		f.printf("func (%s) statement() {}\n", t)
		if slices.Contains(rowsets, t) {
			f.printf("func (%s) rowset() {}\n", t)
		}
		// The methods render their receiver in place. Passing it to the
		// package-level functions would copy the builder into a Statement and
		// again out of it.
		f.printf("\n// append%s renders the builder b points to.\n", t)
		f.printf(`func append%s(sql []byte, args []any, b *%s, options Options) ([]byte, []any, error) {
	w, ok := newRenderer(sql, args, options)
	if ok {
		if outerHasWindow, opened := w.openStatement(); opened {
			w.%s(b)
			w.closeStatement(outerHasWindow)
		}
		if w.err != nil {
			w.errorPath(%q, 0)
		}
	}
	return w.result(sql, args)
}
`, t, t, k.render, k.label)
		const owned = "var scratch [ownedSQLScratch]byte; return ownedSQL(append%s(scratch[:0], nil, &b, %s))"
		f.method(t, "ToSQL", "", "(string, []any, error)", fmt.Sprintf(owned, t, "Options{}"))
		f.method(t, "ToSQLWith", "options Options", "(string, []any, error)", fmt.Sprintf(owned, t, "options"))
		f.method(t, "AppendSQL", "sql []byte, args []any", "([]byte, []any, error)", fmt.Sprintf("return append%s(sql, args, &b, Options{})", t))
		f.method(t, "AppendWith", "sql []byte, args []any, options Options", "([]byte, []any, error)", fmt.Sprintf("return append%s(sql, args, &b, options)", t))
		f.write("\n")
	}

	f.write("// dispatchStatement renders s, which arrives as a value in an interface and is\n// copied out once.\n")
	f.write("func (w *renderer) dispatchStatement(s Statement) {\nswitch b := s.(type) {\n")
	for _, k := range statementKinds {
		f.printf("case %s:\nw.%s(&b)\n", k.builder, k.render)
	}
	f.write("default:\nw.fail(ErrInvalid, \"statement\", \"nil statement\")\n}\n}\n\n")

	f.write("// statementLabel names s in an error path.\n")
	f.write("func statementLabel(s Statement) string {\nswitch s.(type) {\n")
	for _, k := range statementKinds {
		f.printf("case %s:\nreturn %q\n", k.builder, k.label)
	}
	f.write("default:\nreturn \"statement\"\n}\n}\n\n")

	f.write("// statementPointee reports whether s is a pointer to a builder and returns the\n")
	f.write("// builder it points to, or nil for a nil pointer.\n")
	f.write("func statementPointee(s Statement) (Statement, bool) {\nswitch p := s.(type) {\n")
	for _, k := range statementKinds {
		f.printf("case *%s:\nif p == nil {\nreturn nil, true\n}\nreturn *p, true\n", k.builder)
	}
	f.write("}\nreturn nil, false\n}\n")
	return f
}

func fluentMethods() *file {
	f := new(file)
	f.write(header)

	// INSERT target columns are selected before a source. The intermediate
	// value deliberately has no statement or clause methods of its own.
	f.doc("Columns", docs["Columns"])
	f.write("func (t InsertTarget) Columns(first string, rest ...string) InsertColumnsTarget { return newInsertColumnsTarget(t.table, first, rest) }\n")
	f.doc("Targets", docs["Targets"])
	f.write("func (t InsertTarget) Targets(first Expr, rest ...Expr) InsertColumnsTarget { return newInsertExprTarget(t.table, first, rest) }\n\n")
	for _, m := range [][4]string{
		{"ValuesSlice", "values []WriteValue", insertRows, "return InsertRows{base: t.base()}.ValuesSlice(values)"},
		{"Rows", "rows ...[]WriteValue", insertRows, "return InsertRows{base: t.base()}.Rows(rows...)"},
		{"Values", "first WriteValue, rest ...WriteValue", insertRows, "return InsertRows{base: t.base()}.Values(first, rest...)"},
		{"From", "source Rowset", insertSelect, "return InsertSelect{base: t.base(), source: ownedRowset(source)}"},
		{"DefaultValues", "", "InsertDefaults", "return InsertDefaults{base: t.base()}"},
	} {
		f.doc(m[0], docs[m[0]])
		f.printf("func (t InsertColumnsTarget) %s(%s) %s { %s }\n", m[0], m[1], m[2], m[3])
	}
	f.write("\n")

	for _, t := range builders {
		f.method(t, "With", "ctes ...WithQuery", "", "b.base.with = extend(b.base.with, ctes...); return b")
		if t != "MergeBuilder" {
			f.method(t, "WithRecursive", "ctes ...WithQuery", "", "b.base.recursive = true; b.base.with = extend(b.base.with, ctes...); return b")
		}
		f.method(t, "Prefix", "parts ...Expr", "", "b.base.prefix = extend(b.base.prefix, parts...); return b")
		f.method(t, "Suffix", "parts ...Expr", "", "b.base.suffix = extend(b.base.suffix, parts...); return b")
		if slices.Contains(insertRoles, t) {
			f.method(t, "Into", "table string", "", "b.base.table = Table(table); return b")
			if slices.Contains(insertOverrideRoles, t) {
				f.method(t, "OverridingSystemValue", "", "", "b.base.overriding = overridingSystemValue; return b")
				f.method(t, "OverridingUserValue", "", "", "b.base.overriding = overridingUserValue; return b")
			}
			f.genericMethod(t, "OnConflict", "[C conflictAction]", "conflict C", "", "setInsertConflict(&b.base, conflict); return b")
			f.method(t, "Returning", "expressions ...Expr", "", "b.base.returning = extend(b.base.returning, expressions...); return b")
			f.method(t, "ReturningCols", "columns ...string", "", "insertReturningCols(&b.base, columns...); return b")
			f.method(t, "ReturningRows", "aliases ReturningAliases", "", "b.base.aliases = aliases; return b")
		}
		if slices.Contains(rowsets, t) {
			f.method(t, "As", "alias string, columns ...string", "Relation", "return Subquery(b, alias, columns...)")
			f.method(t, "OrderBy", "terms ...Order", "", "b.tail.order = extend(b.tail.order, terms...); return b")
			f.method(t, "Limit", "count int", "", "return b.LimitExpr(limitValue(count))")
			f.method(t, "LimitExpr", "count Expr", "", "b.tail = b.tail.withLimit(limitCount, count); return b")
			f.method(t, "Offset", "count int", "", "return b.OffsetExpr(limitValue(count))")
			f.method(t, "OffsetExpr", "count Expr", "", "b.tail.offset = count; b.tail.hasOffset = true; return b")
			f.method(t, "LimitAll", "", "", "b.tail = b.tail.withLimit(limitAll, Expr{}); return b")
			f.method(t, "LimitWithTies", "count int", "", "return b.LimitWithTiesExpr(limitValue(count))")
			f.method(t, "LimitWithTiesExpr", "count Expr", "", "b.tail = b.tail.withLimit(limitWithTies, count); return b")
			if slices.Contains(lockable, t) {
				f.method(t, "Lock", "clauses ...LockClause", "", "b.tail.locks = extend(b.tail.locks, clauses...); return b")
			}
		}
		f.write("\n")
	}
	return f
}

// tuples stops at degree four: arbitrary-degree Row needs no generation, and
// each generated degree keeps the Go type of every value.
func tuples() *file {
	f := new(file)
	f.write(header)
	operators := [][2]string{{"Eq", "="}, {"Ne", "<>"}, {"Lt", "<"}, {"Lte", "<="}, {"Gt", ">"}, {"Gte", ">="}}
	for degree := 2; degree <= 4; degree++ {
		var params, types, fields, values, actual, exprs []string
		for i := range degree {
			upper, lower := string(rune('A'+i)), string(rune('a'+i))
			params = append(params, upper+" any")
			types = append(types, upper)
			fields = append(fields, fmt.Sprintf("%s Field[%s]", lower, upper))
			values = append(values, lower+" "+upper)
			actual = append(actual, lower)
			exprs = append(exprs, lower+".expr")
		}
		name := fmt.Sprintf("Tuple%dExpr", degree)
		instance := fmt.Sprintf("%s[%s]", name, strings.Join(types, ", "))
		f.printf("// %s is a statically typed SQL row of degree %d. Its type parameters describe the Go value types accepted by its comparison methods; they do not validate SQL types or nullability.\n", name, degree)
		f.printf("type %s[%s] struct{ row RowExpr }\n", name, strings.Join(params, ", "))
		f.doc(fmt.Sprintf("Tuple%d", degree), fmt.Sprintf("constructs a degree-%d row from typed fields in argument order.", degree))
		f.printf("func Tuple%d[%s](%s) %s { return %s{row: Row(%s)} }\n", degree, strings.Join(params, ", "), strings.Join(fields, ", "), instance, instance, strings.Join(exprs, ", "))
		f.doc("Expr", "returns the underlying row expression.")
		f.printf("func (r %s) Expr() Expr { return r.row.Expr() }\n", instance)
		for _, op := range operators {
			f.doc(op[0]+"Values", fmt.Sprintf("compares r with a row of bound values using SQL %s. Values are bound in argument order.", op[1]))
			f.printf("func (r %s) %sValues(%s) Condition { return r.row.compareValues(%q, %s) }\n", instance, op[0], strings.Join(values, ", "), op[1], strings.Join(actual, ", "))
		}
	}
	return f
}

