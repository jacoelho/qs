// statementKind is one concrete statement type: the renderer method that
// writes it and the label it contributes to an error path.
type statementKind struct{ builder, render, label string }

// statementKinds is the only list of statement types. The rendering entry
// points, the dispatch over a Statement and the error-path label are all
// written from it, so a new statement type cannot be added to one and missed
// in another.
var statementKinds = []statementKind{
	{selectBuilder, "selectStatement", "SELECT"},
	{insertRows, "insertRows", insertLabel},
	{insertSelect, "insertSelect", insertLabel},
	{insertAssignments, "insertAssignments", insertLabel},
	{insertDefaults, "insertDefaults", insertLabel},
	{"UpdateBuilder", "updateStatement", "UPDATE"},
	{"DeleteBuilder", "deleteStatement", "DELETE"},
	{"MergeBuilder", "mergeStatement", "MERGE"},
	{setBuilder, "setOperation", "set operation"},
	{valuesBuilder, "valuesStatement", "VALUES"},
	{tableBuilder, "tableStatement", "TABLE"},
	{trustedStatement, "sqlStatement", "statement fragment"},
}

var (
	rowsets             = []string{selectBuilder, setBuilder, valuesBuilder, tableBuilder}
	insertRoles         = []string{insertRows, insertSelect, insertAssignments, insertDefaults}
	insertOverrideRoles = []string{insertRows, insertSelect, insertAssignments}
	lockable            = []string{selectBuilder, tableBuilder}
	// builders carry statement-level clauses. The trusted statement has none.
	builders = clauseBuilders()
)

func clauseBuilders() []string {
	var names []string
	for _, k := range statementKinds {
		if k.builder != trustedStatement {
			names = append(names, k.builder)
		}
	}
	return names
}

