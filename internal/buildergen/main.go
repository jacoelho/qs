// Command buildergen writes the methods that every statement builder repeats:
// rendering entry points, statement-level clauses, the shared query tail and
// the INSERT roles, plus the fixed-degree typed tuples. Go has no self type,
// so a method that returns its receiver's own type must be declared once per
// builder; generating them keeps the copies identical.
//
// Run it from the module root: go run ./internal/buildergen. With -check it
// reports stale output without writing.
