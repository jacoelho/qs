func sqljsonMethods() *file {
	f := new(file)
	f.write(header)
	for _, form := range jsonForms {
		t := form.builder
		if slices.Contains(form.families, jsonExpr) {
			f.printf("func (%s) exprNode() {}\n", t)
			f.printf("func (%s) qxExpression() {}\n\n", t)
		}
		for _, family := range form.families {
			for _, c := range jsonClauses[family] {
				f.jsonMethod(t, c)
			}
		}
		f.jsonBehaviors(t, eventEmpty, form.onEmpty)
		f.jsonBehaviors(t, eventError, form.onError)
	}
	return f
}

func (f *file) jsonMethod(builder string, c jsonClause) {
	result := c.result
	if result == "" {
		result = builder
	}
	f.doc(c.name, c.doc)
	f.printf("func (b %s) %s(%s) %s { %s }\n", builder, c.name, c.params, result, c.body)
}

// jsonBehaviors declares one method per behavior a form accepts for event.
func (f *file) jsonBehaviors(builder, event string, behaviors []string) {
	for _, behavior := range behaviors {
		c := jsonClause{
			name: behavior + "On" + event,
			body: fmt.Sprintf("b.on%s = behavior(jsonBehavior%s); return b", event, behavior),
			doc:  fmt.Sprintf("returns b made to %s %s, replacing an earlier ON %s clause.", jsonBehaviorResults[behavior], jsonEvents[event], strings.ToUpper(event)),
		}
		if behavior == behaviorDefault {
			c.params = "value Expr"
			c.body = fmt.Sprintf("b.on%s = defaultBehavior(value); return b", event)
			c.doc += " PostgreSQL accepts a constant such as LiteralInt(0), a function call or an operator expression as value, with no column reference in it; a value that is a column fails rendering. Under the extended query protocol PostgreSQL also refuses a value that is only a bound parameter, which qs leaves to the server."
		}
		f.jsonMethod(builder, c)
	}
}

func emit(path string, f *file, check bool) error {
	formatted, err := format.Source(f.source)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if !check {
		//nolint:gosec // Generated Go source is readable like the rest of the tree.
		return os.WriteFile(path, formatted, 0o644)
	}
	//nolint:gosec // path is one of the fixed output names in main.
	current, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !bytes.Equal(current, formatted) {
		return fmt.Errorf("%s is stale; run make generate", path)
	}
	return nil
}

func main() {
	check := flag.Bool("check", false, "report stale output without writing")
	flag.Parse()
	for _, output := range []struct {
		file *file
		path string
	}{
		{statementMethods(), "statement_methods.go"},
		{fluentMethods(), "fluent.go"},
		{tuples(), "tuple.go"},
		{sqljsonMethods(), "sqljson_methods.go"},
	} {
		if err := emit(output.path, output.file, *check); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
